import * as fs from "node:fs";
import * as path from "node:path";
import {
  compileContent,
  NOT_A_PROJECT,
  renderPagesWith,
  type ContentSource,
} from "./compile-core.js";
import { SHARED_DIR } from "./links.js";
import { renderBody } from "./render.js";
import type { RenderPolicy } from "./sanitize.js";
import type {
  CompiledPage,
  DocsFolder,
  DocsPage,
  DocsProject,
} from "./types.js";
import { VARIANT_GROUPS } from "./variants.js";
import { writeIfChanged } from "./write.js";

/** Markdown paths below `dir`, relative to it, extension stripped, slash-separated. */
function walk(dir: string, prefix = ""): string[] {
  const found: string[] = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (entry.name.startsWith(".")) continue;
    const rel = prefix ? `${prefix}/${entry.name}` : entry.name;
    if (entry.isDirectory()) {
      found.push(...walk(path.join(dir, entry.name), rel));
    } else if (entry.name.endsWith(".md")) {
      found.push(rel.replace(/\.md$/, ""));
    }
  }
  return found;
}

/** A content root on disk. */
function diskSource(contentRoot: string): ContentSource {
  return {
    projects: () =>
      fs
        .readdirSync(contentRoot, { withFileTypes: true })
        .filter(
          (entry) =>
            entry.isDirectory() &&
            !entry.name.startsWith(".") &&
            entry.name !== SHARED_DIR &&
            !NOT_A_PROJECT.has(entry.name),
        )
        .map((entry) => entry.name),
    pages: (project) => walk(path.join(contentRoot, project)),
    shared: () => {
      const sharedDir = path.join(contentRoot, SHARED_DIR);
      return fs.statSync(sharedDir, { throwIfNoEntry: false })?.isDirectory()
        ? walk(sharedDir)
        : [];
    },
    read: (file) => fs.readFileSync(path.join(contentRoot, file), "utf-8"),
  };
}

/**
 * Compiles the content root `contentRoot` (see `compileContent` for the rules:
 * projects, `_shared` mounts, sections, folder settings). The file system half
 * of the compiler; the build, `docs-kit check` and the candidate pipeline's
 * fetched directory all come through here.
 */
export function compileDocs(contentRoot: string): {
  projects: DocsProject[];
  pages: CompiledPage[];
  folders: DocsFolder[];
} {
  return compileContent(diskSource(contentRoot));
}

/** Renders every compiled page's HTML, highlighted, dropping what only the build needed. */
export function renderPages(
  compiled: readonly CompiledPage[],
  policyFor?: (page: CompiledPage) => RenderPolicy,
): Promise<DocsPage[]> {
  return renderPagesWith(renderBody, compiled, policyFor);
}

/**
 * A JavaScript expression that evaluates to `value`, written so the module's
 * source never contains the two characters `/*`.
 *
 * They read as the start of a block comment to anything that strips comments
 * from the source with a regex, and vite-plugin-commonjs (which vinext runs
 * over every project file that mentions `require(` or `\u`) does exactly that,
 * with a lazy `(.|[\r\n])*?` that overflows the regex engine's stack when a
 * `/*` has no `*\/` close nearby. The compiled docs are one 10 MB module of
 * page text, so a page that mentions `packages/*` after the last `*\/` broke
 * the platform's build and dev server.
 *
 * A string literal does not help: vinext re-prints the module before that
 * plugin sees it, and the printer writes `"\u002a"` back as `"*"`. So the data
 * is JSON text inside one string literal, with `*` after a `/` escaped at the
 * JSON level (`\u002a`, which survives as backslash-u text) and parsed at load.
 * `JSON.parse` of a large string is also cheaper at Worker startup than
 * evaluating the same data as an object literal.
 */
export function moduleExpression(value: unknown): string {
  const json = JSON.stringify(value).replaceAll("/*", "/\\u002a");
  return `JSON.parse(${JSON.stringify(json)})`;
}

/**
 * Writes the compiled content as an ESM module plus its declarations.
 *
 * The output is written directly rather than run through tsc, so the content
 * package needs no TypeScript toolchain: `docs/` stays markdown plus a
 * package.json, with none of this code sitting alongside it.
 */
export async function emitDocsModule(
  contentRoot: string,
  outDir: string,
): Promise<number> {
  const { projects, pages: compiled, folders } = compileDocs(contentRoot);
  const pages = await renderPages(compiled);

  writeIfChanged(
    path.join(outDir, "index.js"),
    `// GENERATED by @devdogsuga/docs-kit — do not edit.
export const projects = ${moduleExpression(projects)};

export const variantGroups = ${moduleExpression(VARIANT_GROUPS)};

export const pages = ${moduleExpression(pages)};

export const folders = ${moduleExpression(folders)};
`,
  );

  writeIfChanged(
    path.join(outDir, "index.d.ts"),
    `// GENERATED by @devdogsuga/docs-kit — do not edit.
import type {
  DocsFolder,
  DocsPage,
  DocsProject,
  VARIANT_GROUPS,
} from "@devdogsuga/docs-kit";

export declare const projects: DocsProject[];
/** The setup axes a page can vary by, their values and labels. */
export declare const variantGroups: typeof VARIANT_GROUPS;
export declare const pages: DocsPage[];
/** Folder settings: the name, order and steps of folders that declare them. */
export declare const folders: DocsFolder[];

export type {
  DocHeading,
  DocsFolder,
  DocsPage,
  DocsProject,
  DocsSection,
  ParsedDocFile,
  VariantGroup,
} from "@devdogsuga/docs-kit";
`,
  );

  return pages.length;
}
