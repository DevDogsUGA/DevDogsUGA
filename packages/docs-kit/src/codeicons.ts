/** The icon for a file block: by `file`'s name first, then by `lang`. */
export function codeIcon(lang: string, file?: string): CodeIcon {
  const name = file?.split("/").pop() ?? "";
  if (/^\.env(\.|$)/.test(name)) return "config";
  const dot = name.lastIndexOf(".");
  const extension = dot > 0 ? name.slice(dot + 1).toLowerCase() : "";
  return BY_EXTENSION[extension] ?? BY_LANG[lang] ?? "code";
}

