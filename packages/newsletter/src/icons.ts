/** A standalone `<svg>` around one icon path, ready to rasterise or inline. */
export function socialIconSvg(
  name: SocialIconName,
  fill: string = PALETTE.ink,
): string {
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 256 256" fill="${fill}"><path d="${SOCIAL_ICON_PATHS[name]}"/></svg>`;
}

/** The same icon as an `<img>` source for the page render, where SVG is safe. */
export function socialIconDataUri(name: SocialIconName): string {
  return `data:image/svg+xml;utf8,${encodeURIComponent(socialIconSvg(name))}`;
}
